-- Helper function to check if current user is admin
CREATE OR REPLACE FUNCTION public.is_admin()
RETURNS BOOLEAN AS $$
BEGIN
    RETURN EXISTS (
        SELECT 1 FROM public.profiles
        WHERE id = auth.uid() AND role = 'admin'
    );
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

-- PROFILES POLICIES
CREATE POLICY "Users can view own profile"
    ON public.profiles FOR SELECT
    USING (auth.uid() = id OR public.is_admin());

CREATE POLICY "Users can update own profile"
    ON public.profiles FOR UPDATE
    USING (auth.uid() = id);

-- WATCH HISTORY POLICIES
CREATE POLICY "Users can manage own watch history"
    ON public.user_watch_history FOR ALL
    USING (auth.uid() = user_id OR public.is_admin());

-- RATINGS POLICIES
CREATE POLICY "Users can manage own ratings"
    ON public.user_ratings FOR ALL
    USING (auth.uid() = user_id OR public.is_admin());

-- WATCHLIST POLICIES
CREATE POLICY "Users can manage own watchlist"
    ON public.user_watchlist FOR ALL
    USING (auth.uid() = user_id OR public.is_admin());

-- FEEDBACK POLICIES
CREATE POLICY "Users can manage own feedback"
    ON public.user_feedback FOR ALL
    USING (auth.uid() = user_id OR public.is_admin());

-- RECOMMENDATION LOGS POLICIES
CREATE POLICY "Users view own logs, Admins view all"
    ON public.user_recommendation_logs FOR SELECT
    USING (auth.uid() = user_id OR public.is_admin());

CREATE POLICY "Users insert recommendation logs"
    ON public.user_recommendation_logs FOR INSERT
    WITH CHECK (auth.uid() = user_id OR user_id IS NULL);

-- ==============================================================================
-- AUTOMATIC PROFILE CREATION TRIGGER ON AUTH SIGNUP
-- ==============================================================================

CREATE OR REPLACE FUNCTION public.handle_new_user()
RETURNS TRIGGER AS $$
BEGIN
    INSERT INTO public.profiles (id, email, display_name, role)
    VALUES (
        NEW.id,
        NEW.email,
        COALESCE(NEW.raw_user_meta_data->>'display_name', split_part(NEW.email, '@', 1)),
        'user'
    );
    RETURN NEW;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

DROP TRIGGER IF EXISTS on_auth_user_created ON auth.users;
CREATE TRIGGER on_auth_user_created
    AFTER INSERT ON auth.users
    FOR EACH ROW EXECUTE FUNCTION public.handle_new_user();

